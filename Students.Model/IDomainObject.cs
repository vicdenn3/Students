namespace Students.Model
{
    /// <summary>
    /// Базовый интерфейс для всех сущностей предметной области (Domain).
    /// Гарантирует, что у любого объекта, с которым работает репозиторий, есть Id.
    /// Именно это позволяет обобщённому репозиторию обращаться к obj.Id,
    /// не зная конкретного типа T.
    /// </summary>
    public interface IDomainObject
    {
        int Id { get; set; }
    }
}
